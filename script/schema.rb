# Writes src/schema.egg: db/schema.sql, the Rails migrations it stands for,
# the schema.rb digest Rails records, and the indexes once-campfire-rust adds.
Encoding.default_external = Encoding::UTF_8
root = File.expand_path("..", __dir__)
rust = File.read(File.join(root, "db/schema.sql"))
def egg_string(s) = '"' + s.gsub("\\", "\\\\\\\\").gsub('"', '\"').gsub("\n", '\n') + '"'
versions = %w[20231215043540 20231220143106 20240110071740 20240115124901 20240130003150 20240130213001
              20240131105830 20240209110503 20250825100957 20250825100958 20250825100959 20251126092013
              20251126115722 20251126130131 20251212154340]
additions = [
  %q{CREATE INDEX IF NOT EXISTS "index_messages_on_room_id_and_created_at" ON "messages" ("room_id", "created_at");},
  %q{CREATE INDEX IF NOT EXISTS "index_messages_on_room_id_and_updated_at" ON "messages" ("room_id", "updated_at");},
]
puts <<~EGG
  // Generated by script/schema.rb from db/schema.sql: do not edit.
  //
  // The schema bin/rails db:prepare gives a fresh database, the migrations
  // it stands for (oldest first), the SHA1 of the schema.rb it was loaded
  // from, and indexes once-campfire-rust adds to every database.

  const SQL = #{egg_string(rust)}

  const VERSIONS = #{egg_string(versions.join(","))}

  const SHA1 = "f75da8dad38bfb179ffd757bd7a7c2b3f818bc29"

  const ADDITIONS = #{egg_string(additions.join("\n"))}
EGG
