# Writes src/static_head.egg: the part of every page's <head> that only the
# assets decide (stylesheet links, the import map, module preloads), taken
# from a page the reference Rails app served. Usage:
#   ruby script/static_head.rb PAGE.html > src/static_head.egg
html = File.read(ARGV[0])
from = html.index('<link rel="stylesheet"') or abort "no stylesheet link"
to = html.index('<script type="module">import "application"</script>') or abort "no import"
to += '<script type="module">import "application"</script>'.length
chunk = html[from...to]
# Rails puts each tag on its own line; keep that, as one Egg string.
lit = chunk.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }.gsub("\n") { "\\n" }
puts "// Generated by script/static_head.rb from a page of the reference Rails app:"
puts "// the stylesheet links, the import map and its module preloads, which only"
puts "// the precompiled assets decide. Do not edit."
puts
puts "const ASSETS = \"#{lit}\""
