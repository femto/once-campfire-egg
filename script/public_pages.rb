# Writes src/public_pages.egg: Rails' public/404.html and 422.html, which
# the Rust app serves for a missing record and a forged request, as Egg
# strings. Usage:
#   ruby script/public_pages.rb ../once-campfire-rust/reference/public > src/public_pages.egg
# Templates and pages are UTF-8 whatever the locale (Debian's is ASCII).
Encoding.default_external = Encoding::UTF_8
dir = ARGV.fetch(0)
lit = ->(s) { s.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }.gsub("\n") { "\\n" }.gsub("\t") { "\\t" } }
puts "// Generated by script/public_pages.rb from Rails' public/ pages. Do not edit."
puts
puts "const NOT_FOUND = \"#{lit.(File.read(File.join(dir, "404.html")))}\""
puts
puts "const UNPROCESSABLE = \"#{lit.(File.read(File.join(dir, "422.html")))}\""
