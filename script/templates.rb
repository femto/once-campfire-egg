# Compiles templates/*.html into one Egg module, src/views.egg: each
# template becomes a function that appends its text to a Buf(u8).
#
#   ruby script/templates.rb > src/views.egg
#
# A template starts with its signature line:
#   <%fn name(a: Allocator, inout out: Buf(u8), m: Message) %>
# and then holds text and tags:
#   <%= expr %>   text, HTML-escaped
#   <%- expr %>   text, as it is (already HTML)
#   <%d expr %>   an integer
#   <% code %>    Egg statements: if/for/while lines, calls, consts
#   <%: code %>   the same, but its line is kept even when the tag is alone on it
# A line holding only a <% code %> tag adds no text: neither the tag's
# indentation nor its line ending. templates/_head.egg goes first: the
# module's uses line and imports.
# Templates and pages are UTF-8 whatever the locale (Debian's is ASCII).
Encoding.default_external = Encoding::UTF_8
dir = File.expand_path("../templates", __dir__)

def literal(s)
  s.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }.gsub("\n") { "\\n" }.gsub("\r") { "\\r" }.gsub("\t") { "\\t" }
end

def compile(path)
  src = File.read(path)
  sig = src[/\A<%fn (.*?) %>\n/, 1] or abort "#{path}: no <%fn ... %> signature line"
  body = src.sub(/\A<%fn .*? %>\n/, "")
  out = ["// #{File.basename(path)}", "fn #{sig} void {"]
  pending = +""
  flush = lambda do
    out << "    a.append_str(&out, \"#{literal(pending)}\")" unless pending.empty?
    pending = +""
  end
  # Code-only lines vanish entirely.
  body = body.gsub(/^[ \t]*(<%[^=\-d#:].*?%>)[ \t]*\n/) { $1 }
  pos = 0
  body.scan(/<%([=\-d#:]?)(.*?)%>/m) do
    m = Regexp.last_match
    pending << body[pos...m.begin(0)]
    pos = m.end(0)
    kind, code = m[1], m[2].strip
    next if kind == "#"
    flush.call
    case kind
    when "=" then out << "    html.escape(a, &out, #{code})"
    when "-" then out << "    a.append_str(&out, #{code})"
    when "d" then out << "    a.append_int(&out, #{code})"
    else code.each_line { |l| out << "    #{l.rstrip}" }
    end
  end
  pending << body[pos..]
  flush.call
  out << "}"
  out.join("\n")
end

puts "// Generated by script/templates.rb from templates/. Do not edit."
puts File.read(File.join(dir, "_head.egg"))
Dir[File.join(dir, "*.html")].sort.each do |path|
  puts
  puts compile(path)
end
